/*
# 009 — حدود رفع الملفات ومنع تكرار البلاغات

## نظرة عامة
1. التحقق من نوع/حجم الملف في الواجهة (React) مفيد لتجربة المستخدم
   فقط، لكنه لا يحمي شيئاً فعلياً — أي شخص يستطيع تجاوزه بإرسال طلب
   مباشر لـ Supabase Storage API. الحماية الحقيقية يجب أن تكون على
   مستوى الخادم (Storage bucket نفسه)، وهذا ما يفعله هذا الملف.
2. منع نفس المستخدم من إرسال أكثر من بلاغ واحد على نفس الفيديو،
   لمنع إغراق قائمة البلاغات في لوحة الإدارة ببلاغات مكررة من نفس الشخص.
*/

-- ============================================================
-- 1) فرض نوع وحجم الملفات المسموح بها فعلياً من طرف الخادم
--    (100 ميجابايت كحد أقصى، صيغ فيديو وصور محددة فقط)
-- ============================================================
UPDATE storage.buckets
SET file_size_limit = 104857600, -- 100 ميجابايت بالبايت
    allowed_mime_types = ARRAY[
      'video/mp4', 'video/webm', 'video/quicktime',
      'image/jpeg', 'image/png', 'image/webp'
    ]
WHERE id = 'videos';

-- ============================================================
-- 2) منع تكرار البلاغات: مستخدم واحد لا يستطيع إرسال أكثر من
--    بلاغ واحد على نفس الفيديو
-- ============================================================
DO $$
BEGIN
  ALTER TABLE reports ADD CONSTRAINT unique_report_per_user_video UNIQUE (reporter_id, video_id);
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
